#pragma once

// Касание и нажим: по сигналу нагрузки на моторы определяется, коснулся ли
// карандаш поверхности и с какой силой давит.
//
// Модуль ничего не знает о железе: на вход — сырые значения регистра нагрузки
// по каждому мотору, на выход — решение. Вся логика поэтому проверяется
// тестами без робота.
//
// Зачем это нужно: сервопривод не доходит до своей цели (мёртвая зона до
// 1.4° по углу, а это миллиметры по карандашу), поэтому «достичь цели по
// положению» нельзя — можно только «упереться в бумагу». Бумага видна по
// нагрузке на моторы, и это единственный сигнал, который отличает
// «карандаш висит в воздухе» от «карандаш пишет по бумаге».

#include <array>
#include <cstddef>
#include <cstdint>

#include "servo_bus.hpp"

namespace so101 {

// Сигнал нагрузки по каждому мотору живёт рядом с числом моторов, то есть
// в servo_bus.hpp; здесь он становится виден под именем пространства.
using ::TorqueSignal;

// Пороги критерия касания.
//
// Единицы — сырые единицы регистра: что именно в них, выясняется замером на
// живой руке (режим --probe), поэтому пороги задаются снаружи, а не зашиты
// в код.
struct ContactOptions {
	// Наименьшее изменение сигнала, при котором касание считается
	// состоявшимся. Ниже — карандаш ещё в воздухе.
	std::int32_t press_min{0};
	// Желаемый уровень нажима: спуск продолжается, пока нагрузка не дойдёт
	// до него. Ноль — нажим не задаётся, поиск останавливается на первом
	// касании.
	//
	// Нажим задаётся нагрузкой, а не глубиной, и это не каприз: глубина
	// задаётся с точностью до мёртвой зоны мотора, а та измеряется в углах
	// суставов и по карандашу составляет миллиметры. Нагрузка — единственная
	// величина, которой можно задать усилие нажима.
	std::int32_t press_target{0};
	// Наибольшее изменение сигнала: выше моторы перегружены. Это
	// предохранитель, а не критерий рисунка. Ноль — предохранителя нет.
	std::int32_t press_max{0};
	// Сколько первых моторов суммируется в уровень: карандаш держат первые
	// четыре (IK-суставы), wrist_roll и gripper в нажатие не входят.
	std::size_t motors{4};
};

// Что происходит с карандашом.
enum class ContactState {
	// Карандаш не касается поверхности: след не остаётся.
	Free,
	// Касается, нажим в норме.
	Touching,
	// Нажим выше предела: моторы перегружены, рисование надо остановить.
	TooHard,
};

struct ContactReading {
	ContactState state{ContactState::Free};
	// Уровень сигнала по учитываемым моторам.
	std::int32_t level{0};
	// Тот же уровень, но без касания (база).
	std::int32_t baseline{0};
	// Изменение уровня относительно базы.
	std::int32_t delta{0};
};

// Модуль числа без переполнения: std::abs от INT32_MIN — неопределённое
// поведение, а значение сигнала к этому прийти может.
[[nodiscard]] std::int32_t signal_magnitude(std::int32_t value);

// Сумма сигнала по первым motors моторам.
//
// Суммируются, а не выбирается максимум: нажим распределён по суставам
// неравномерно, и сумма отражает, сколько всего момента держит рука. Единицы
// суммы зависят от числа моторов — это учитывается при подборе порогов.
[[nodiscard]] std::int32_t sum_signal(const TorqueSignal& signal,
                                       std::size_t motors);

// Решение о касании по сигналу и базе.
//
// Нажатие считается по изменению сигнала относительно базы: сама по себе
// нагрузка на моторы включает вес руки, и вес меняется по мере хода по
// окружности. Реакция бумаги — это именно изменение.
[[nodiscard]] ContactReading evaluate_contact(const TorqueSignal& signal,
                                               const TorqueSignal& baseline,
                                               const ContactOptions& options);

}  // namespace so101
