#pragma once

// Что и где рисуем: плоскость рисования и окружность.
//
// Модуль ничего не знает о железе и о том, как рисование выполняется —
// только геометрия и файл плоскости. Исполнение живёт в
// drawing_execution.hpp.

#include <Eigen/Dense>

#include <cstddef>
#include <string>
#include <vector>

namespace so101 {

// Плоскость рисования, измеренная один раз и сохранённая в файл.
//
// tcp_height_m — высота точки TCP в момент касания поверхности. Длина
// карандаша в неё не входит: остриё лежит на оси инструмента на расстоянии
// L от TCP, и при вертикальном инструменте оно на L ниже TCP — и при
// захвате, и при рисовании. Высота TCP поэтому переносится на рисование
// без поправок, а длина карандаша не нужна вовсе.
//
// contact_x_m, contact_y_m — точка касания в базовой системе.
//
// tilt_deg — наклон инструмента в момент касания. Ошибка высоты от него
// пропорциональна L(1 - cos θ), поэтому наклон записывается: по нему видно,
// насколько захват точен.
struct Plane {
	double tcp_height_m{0.0};
	double contact_x_m{0.0};
	double contact_y_m{0.0};
	double tilt_deg{0.0};
};

// Окружность в горизонтальной плоскости.
struct CircleSpec {
	double center_x_m{0.0};
	double center_y_m{0.0};
	double radius_m{0.0};
	std::size_t points{36};
};

// Цели TCP по окружности.
//
// press_m — нажатие карандаша на бумагу: цель по высоте ниже плоскости на
// столько, чтобы карандаш писал. Учтём, что прижатие упирается в бумагу и
// моторы сопротивляются, поэтому значение по умолчанию маленькое.
//
// Точки идут по часовой стрелке, начиная с ближайшей к текущему положению:
// первый ход получается коротким, рука не дёргается через пол-оборота.
[[nodiscard]] std::vector<Eigen::Vector3d> circle_targets(
    const Plane& plane, const CircleSpec& circle, double press_m,
    const Eigen::Vector3d& current_position);

// Пишет плоскость в файл. Запись атомарная: сначала во временный файл,
// потом переименование. Оборванная запись не оставит после себя мусор,
// который потом прочитался бы как плоскость.
[[nodiscard]] bool save_plane(const std::string& path, const Plane& plane,
                              std::string& error);

// Читает плоскость из файла.
[[nodiscard]] bool load_plane(const std::string& path, Plane& plane,
                              std::string& error);

}  // namespace so101
